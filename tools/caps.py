#!/usr/bin/env python3
"""POCKET KNIFE – upper limits for Python packages in the weekly update (used by tools/pin-versions.sh --update).

Principle "no version jump": every package stays on its major version (cryptography 50.x stays 50.x), packages before
1.0 on their minor version (fastapi 0.155.x stays 0.155.x) - bug and security fixes within that still come in.
Exception: calendar versions (certifi 2026.10.19, tzdata 2026.1) - every new version there is a pure data update
(e.g. root certificates) and must always come along.

  python3 tools/caps.py lock  requirements.lock      → upper limits of all packages (for requirements.caps)
  python3 tools/caps.py build build-requirements.txt  → the same file with ranges instead of ==, comments stay

A jump to a new major version only deliberately: PK_ALLOW_MAJOR=1 tools/pin-versions.sh --update (with a full test).
"""
import re
import sys

VER = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==([0-9][^\s;#]*)")


def cap(version):
    """Upper limit ("<51", "<0.156") or None (calendar version / not readable)."""
    nums = [int(x) for x in re.findall(r"\d+", version.split("+")[0])[:2]]
    if not nums:
        return None
    if nums[0] >= 1900:  # calendar version
        return None
    if nums[0] == 0:
        return f"<0.{(nums[1] if len(nums) > 1 else 0) + 1}"
    return f"<{nums[0] + 1}"


def line_for(name, version):
    c = cap(version)
    return f"{name}>={version},{c}" if c else f"{name}>={version}"


def lock_caps(text):
    out = ["# Upper limits for the weekly update - generated by tools/caps.py from requirements.lock.",
           "# Every package stays on its major version (before 1.0: minor version); calendar versions have no limit.",
           "# New major versions only deliberately: PK_ALLOW_MAJOR=1 tools/pin-versions.sh --update"]
    for raw in text.splitlines():
        m = VER.match(raw.strip())
        if m:
            out.append(line_for(m.group(1), m.group(2)))
    return "\n".join(out) + "\n"


def build_ranges(text):
    out = []
    for raw in text.splitlines():
        s = raw.strip()
        m = VER.match(s)
        if m:
            out.append(line_for(m.group(1), m.group(2)))
        elif s.startswith("#") or not s:
            out.append(raw)
        else:
            out.append(re.split(r"[=<>!~ ]", s, maxsplit=1)[0])  # without a version: leave as is (name only)
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    if len(sys.argv) != 3 or sys.argv[1] not in ("lock", "build"):
        print(__doc__)
        sys.exit(2)
    t = open(sys.argv[2], encoding="utf-8").read()
    sys.stdout.write(lock_caps(t) if sys.argv[1] == "lock" else build_ranges(t))
